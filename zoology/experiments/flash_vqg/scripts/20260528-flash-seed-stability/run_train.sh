export FOX_REMOTE_READ_TOPK="${FOX_REMOTE_READ_TOPK:-2}"
export FOX_GD_RESIDUAL_WRITE_TOPK="${FOX_GD_RESIDUAL_WRITE_TOPK:-4}"
